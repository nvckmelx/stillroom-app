// Builds the Android/iOS web bundle (www/) from the website client in server/public.
// One client, one catalog: the app loads published tracks from the CMS API at runtime, so new music needs no rebuild.
//
//   STILLROOM_API_BASE=https://example.com/api/v1 node scripts/build-app.mjs
//
// Without STILLROOM_API_BASE the app still works: it plays the catalog bundled in assets/data/catalog.json (offline mode).
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'server', 'public');
const out = join(root, 'www');
const api = (process.env.STILLROOM_API_BASE || '').trim().replace(/\/+$/, '');
const site = (process.env.STILLROOM_SITE_URL || api.replace(/\/api\/v1$/, '')).replace(/\/+$/, '');

if (api && !/^https:\/\//.test(api) && process.env.STILLROOM_ALLOW_HTTP !== '1') {
  console.error('STILLROOM_API_BASE must be an https:// address, e.g. https://example.com/api/v1');
  process.exit(1);
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(join(src, 'assets'), join(out, 'assets'), { recursive: true });

let html = readFileSync(join(src, 'app.html'), 'utf8');
html = html
  .replace('<!--SEO-->', '')
  .replace('<!--BOOT-->', '')
  .replace('<!--SSR-->', '')
  .replace(/<link rel="manifest"[^>]*>\n?/, '')
  .replace(/<link rel="modulepreload"[^>]*>\n?/, '');
writeFileSync(join(out, 'index.html'), html);

writeFileSync(join(out, 'assets', 'js', 'config.js'), `/* Generated by scripts/build-app.mjs — do not edit. */
export const CONFIG = {
  apiBase: ${JSON.stringify(api ? api : '/__offline__')},
  router: 'hash',
  fallbackCatalog: '/assets/data/catalog.json',
  alwaysRefresh: true,
  platform: 'app',
  siteUrl: ${JSON.stringify(site)},
};
`);

if (!existsSync(join(out, 'assets', 'data', 'catalog.json'))) {
  console.error('Missing server/public/assets/data/catalog.json (run: php server/bin/export-catalog.php)');
  process.exit(1);
}
console.log(`www/ built. API: ${api || 'none (offline catalog only)'}`);
